import { readdir, readFile, writeFile } from "node:fs/promises";

const migrations = new URL("./migrations/", import.meta.url);
const files = (await readdir(migrations)).filter((name) => /^\d{3}_.*\.sql$/.test(name)).sort();
const sections = await Promise.all(files.map(async (name) =>
  `-- Migration: ${name}\n${(await readFile(new URL(name, migrations), "utf8")).trim()}\n`,
));
const header = `-- Generated by generate-setup.mjs from the ordered migrations. Do not edit by hand.
-- FRESH Supabase projects only. Never run this against an existing MoneyLai database.
-- After creating Auth users, replace sample emails in BOOTSTRAP_ROLES.sql and run it separately.

`;
await writeFile(new URL("./SETUP_FRESH.sql", import.meta.url), header + sections.join("\n"));
console.log(`Generated SETUP_FRESH.sql from ${files.length} migrations.`);
